async function loadTranslations() {
  const currentLang = sessionStorage.getItem('expertImmoLang') || 'fr';
  switchLanguage(currentLang);
}

function switchLanguage(lang) {
  // Update session storage
  sessionStorage.setItem('expertImmoLang', lang);

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Update all data-i18n nodes (only text content, no safe HTML yet to prevent XSS, but we can do innerHTML if trusted)
  document.querySelectorAll('[data-i18n]:not(input):not(textarea)').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      // Use innerHTML because some translations have <strong> tags
      el.innerHTML = translations[lang][key];
    }
  });

  // Update placeholders
  document.querySelectorAll('input[data-i18n], textarea[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Toggle explicit language blocks (useful for legal pages)
  document.querySelectorAll('.lang-fr').forEach(el => {
    el.style.display = lang === 'fr' ? '' : 'none';
  });
  document.querySelectorAll('.lang-en').forEach(el => {
    el.style.display = lang === 'en' ? '' : 'none';
  });

  // Update switcher UI
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

